import contextlib
import io
import unittest

import release_notes
from source_descriptor import DATASETS_DIR, load_descriptor

TERMINAL_BENCH_SOURCE = DATASETS_DIR / "terminal-bench" / "2.0" / "source.yaml"
PINNED_MIRROR_SOURCE = DATASETS_DIR / "terminal-bench" / "2.0.1" / "source.yaml"
GENERATED_SOURCE = DATASETS_DIR / "humaneval-plus" / "1.0" / "source.yaml"
BUILT_DIGEST = "sha256:" + "9" * 64
REPOSITORY = "ghcr.io/node-q/hbench-datasets/terminal-bench"
DIGEST = "sha256:" + "0123456789abcdef" * 4
HBENCH_VERSION = "v0.3.0"
RUN_URL = "https://github.com/node-q/hbench-datasets/actions/runs/1"


class ReleaseNotesTest(unittest.TestCase):
    def setUp(self):
        self.descriptor = load_descriptor(TERMINAL_BENCH_SOURCE)

    def notes(self):
        return release_notes.release_notes(self.descriptor, REPOSITORY, DIGEST, HBENCH_VERSION, RUN_URL)

    def test_tag_and_title_name_the_dataset_version(self):
        self.assertEqual(release_notes.release_tag(self.descriptor), "terminal-bench-2.0")
        self.assertEqual(
            release_notes.release_title(self.descriptor), "Terminal-Bench 2.0 (terminal-bench@2.0)"
        )

    def test_notes_carry_the_reference_digest_and_licence(self):
        notes = self.notes()
        self.assertIn(f"`{REPOSITORY}:2.0`", notes)
        self.assertIn(f"`{DIGEST}`", notes)
        self.assertIn("Apache-2.0", notes)
        self.assertIn("- Tasks: 89", notes)

    def test_notes_show_how_to_run_and_verify_by_digest(self):
        notes = self.notes()
        self.assertIn("hbench run -d terminal-bench@2.0 --registry oci://ghcr.io/node-q/hbench-datasets", notes)
        self.assertIn(f"cosign verify {REPOSITORY}@{DIGEST}", notes)
        self.assertIn(f"gh attestation verify oci://{REPOSITORY}@{DIGEST}", notes)

    def test_notes_keep_the_citation_and_attribution(self):
        notes = self.notes()
        self.assertIn("```bibtex", notes)
        self.assertIn("@misc{tbench_2025", notes)
        self.assertIn("## Attribution", notes)

    def test_mirrored_version_notes_show_how_to_verify_a_mirrored_image(self):
        descriptor = load_descriptor(PINNED_MIRROR_SOURCE)
        notes = release_notes.release_notes(descriptor, REPOSITORY, DIGEST, HBENCH_VERSION, RUN_URL)
        self.assertEqual(release_notes.release_tag(descriptor), "terminal-bench-2.0.1")
        self.assertIn(f"`{REPOSITORY}:2.0.1`", notes)
        self.assertIn("pinned by digest to `ghcr.io/node-q/hbench-envs/terminal-bench`", notes)
        self.assertIn("`images.lock.json` (attached)", notes)
        self.assertIn("cosign verify ghcr.io/node-q/hbench-envs/terminal-bench@sha256:<digest>", notes)
        self.assertIn(f"--certificate-identity-regexp '{release_notes.MIRROR_CERTIFICATE_IDENTITY_REGEXP}'", notes)
        self.assertEqual(
            release_notes.MIRROR_CERTIFICATE_IDENTITY_REGEXP,
            "^https://github.com/node-q/hbench-datasets/.github/workflows/mirror-images.yml@",
        )
        self.assertIn("the only difference from terminal-bench@2.0", notes)

    def test_upstream_pinned_notes_say_the_images_are_not_mirrored(self):
        descriptor = load_descriptor(PINNED_MIRROR_SOURCE)
        descriptor["environment"]["policy"] = "pinned-upstream"
        notes = release_notes.release_notes(descriptor, REPOSITORY, DIGEST, HBENCH_VERSION, RUN_URL)
        self.assertIn("Each task's `docker_image` is `alexgshaw/{task}:20251031`, pinned by its digest.", notes)
        self.assertIn("The images are not mirrored.", notes)
        self.assertNotIn("mirror-images.yml", notes)

    def test_generated_version_notes_name_the_upstream_files_and_how_to_verify_the_built_image(self):
        descriptor = load_descriptor(GENERATED_SOURCE)
        entry = {
            "source": "ghcr.io/node-q/hbench-envs:humaneval-plus-1.0",
            "source_digest": BUILT_DIGEST,
            "pinned": f"ghcr.io/node-q/hbench-envs@{BUILT_DIGEST}",
        }
        notes = release_notes.release_notes(
            descriptor, REPOSITORY, DIGEST, HBENCH_VERSION, RUN_URL, {"humaneval-plus-0": entry}
        )
        self.assertIn("- Generated by `adapters/humaneval_plus` in this repository from:", notes)
        self.assertIn("(sha256 `272720b90ac375502c8ed23cd791c2a93dfb22a911641a494da74a426c09f101`)", notes)
        self.assertIn(f"cosign verify ghcr.io/node-q/hbench-envs@{BUILT_DIGEST} \\", notes)
        self.assertIn(release_notes.BUILD_IMAGES_CERTIFICATE_IDENTITY_REGEXP, notes)

    def test_command_line_prints_the_requested_field(self):
        output = io.StringIO()
        with contextlib.redirect_stdout(output):
            release_notes.main(
                [
                    "--source",
                    str(TERMINAL_BENCH_SOURCE),
                    "--repository",
                    REPOSITORY,
                    "--digest",
                    DIGEST,
                    "--hbench-version",
                    HBENCH_VERSION,
                    "--run-url",
                    RUN_URL,
                    "--field",
                    "tag",
                ]
            )
        self.assertEqual(output.getvalue(), "terminal-bench-2.0\n")


if __name__ == "__main__":
    unittest.main()
